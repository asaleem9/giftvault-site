// Generates lib/brand-cards.ts from the app's merchant catalog so card colours on the site match the app.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const appDir = process.env.GIFTVAULT_APP_DIR ?? resolve(process.cwd(), "../giftcard-manager");
const src = resolve(appDir, "GiftVault/Packages/GiftVaultCore/Sources/GiftVaultCore/Resources/merchants.json");
const merchants = JSON.parse(readFileSync(src, "utf8"));

const rows = merchants.map((m) => ({
  id: m.id,
  name: m.name,
  start: m.gradientStart,
  end: m.gradientEnd,
  ink: m.ink,
  category: m.category,
}));

const out = `// Generated by scripts/extract-brand.mjs from the app's merchant catalog. Do not edit by hand.
export type BrandCard = {
  id: string;
  name: string;
  start: string;
  end: string;
  ink: string;
  category: string;
};

export const brandCards: readonly BrandCard[] = ${JSON.stringify(rows, null, 2)} as const;

export const brandCardById = new Map(brandCards.map((card) => [card.id, card]));
`;
writeFileSync(resolve(process.cwd(), "lib/brand-cards.ts"), out);
console.log(`wrote lib/brand-cards.ts with ${rows.length} merchants`);
