// Copies and optimises screenshots from the app repository into public/screens.
// Sources stay in the app repo; only derived AVIF/WebP files are committed here.
import sharp from "sharp";
import { mkdirSync, readdirSync, existsSync } from "node:fs";
import { resolve, join } from "node:path";

const appDir = process.env.GIFTVAULT_APP_DIR ?? resolve(process.cwd(), "../giftcard-manager");
const outDir = resolve(process.cwd(), "public/screens");
mkdirSync(outDir, { recursive: true });

// Evidence screenshots carry a UUID suffix, so match by prefix.
function byPrefix(dir, prefix) {
  const full = join(appDir, dir);
  const hit = readdirSync(full).find((f) => f.startsWith(prefix) && f.endsWith(".png"));
  if (!hit) throw new Error(`no file starting with "${prefix}" in ${full}`);
  return join(full, hit);
}

const store = (n) => join(appDir, `Marketing/Screenshots/iphone-6.9/${n}`);
const ev = (dir, prefix) => byPrefix(`Testing/evidence/${dir}`, prefix);

/** name → source. Portrait phone shots share one aspect (0.46), so the site uses one frame for all of them. */
const screens = {
  "cards": store("store-01-cards.png"),
  "detail": store("store-02-detail.png"),
  "register": store("store-03-register.png"),
  "spend": store("store-04-spend.png"),
  "expiring": store("store-05-expiring.png"),
  "detail-revealed": ev("baseline", "testDetailRevealsNumberAndPIN 03"),
  "register-face": ev("baseline", "testShowAtRegisterFlipsToBarcode 10"),
  "search": ev("baseline", "testSearchFiltersCards 16"),
  "onboarding-1": ev("personas", "testP2FirstCard 01"),
  "onboarding-2": ev("personas", "testP2FirstCard 02"),
  "onboarding-3": ev("personas", "testP2FirstCard 03"),
  "store-picker": ev("personas", "testP2FirstCard 05"),
  "digital": ev("p9p4", "testP4DigitalCodes 01"),
  "amazon-register": ev("p9p4", "testP4DigitalCodes 04"),
  "spotify-register": ev("p9p4", "testP4DigitalCodes 08"),
  "settings": ev("personas", "testP6Privacy 01"),
  "ja": ev("personas", "testP5Japanese 01"),
  "ar": ev("personas", "testP5Arabic 01"),
  "volume": ev("personas", "testVolumeScrollAndSearch 01"),
  "landscape": ev("baseline", "testLandscapeLayoutStillShowsCards 19"),
  "duo-list": ev("duo", "testP8DuoLayout 01"),
  "duo-detail": ev("duo", "testP8DuoLayout 02"),
  "duo-register": ev("duo", "testP8DuoLayout 03"),
};

// Widths to emit (CSS px × DPR). Portrait phones render at most ~420 CSS px wide on the site.
const widths = [420, 840, 1260];

const manifest = {};
for (const [name, src] of Object.entries(screens)) {
  if (!existsSync(src)) throw new Error(`missing ${src}`);
  const meta = await sharp(src).metadata();
  manifest[name] = { width: meta.width, height: meta.height };
  for (const w of widths) {
    const target = Math.min(w, meta.width);
    const base = sharp(src).resize({ width: target, withoutEnlargement: true });
    await base.clone().avif({ quality: 58, effort: 6 }).toFile(join(outDir, `${name}-${w}.avif`));
    await base.clone().webp({ quality: 80 }).toFile(join(outDir, `${name}-${w}.webp`));
  }
  process.stdout.write(`${name} `);
}
console.log();

// App icon → favicon set and OG base.
const icon = join(appDir, "GiftVault/GiftVault/Assets.xcassets/AppIcon.appiconset/AppIcon.png");
const iconOut = resolve(process.cwd(), "app");
await sharp(icon).resize(512).png().toFile(join(iconOut, "icon.png"));
await sharp(icon).resize(180).png().toFile(join(iconOut, "apple-icon.png"));
await sharp(icon).resize(1024).webp({ quality: 90 }).toFile(join(outDir, "app-icon.webp"));

const { writeFileSync } = await import("node:fs");
writeFileSync(
  resolve(process.cwd(), "lib/screens.ts"),
  `// Generated by scripts/build-images.mjs. Do not edit by hand.
export const screenWidths = ${JSON.stringify(widths)} as const;
export const screens = ${JSON.stringify(manifest, null, 2)} as const;
export type ScreenName = keyof typeof screens;
`,
);
console.log(`wrote ${Object.keys(manifest).length} screens to public/screens and lib/screens.ts`);
