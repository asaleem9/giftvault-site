// Renders the HyperFrames compositions under hyperframes/ and publishes them into public/media and public/compositions.
// Run: npm run media   (needs ffmpeg, Chrome via the HyperFrames CLI, and the sharp devDependency).
// ONLY=launch-film,wallet-loop npm run media   re-renders just those and keeps the other entries in lib/media.ts.
// This Mac's ffmpeg has no libwebp or libaom, so posters go PNG → sharp → WebP.
import { execFileSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import sharp from "sharp";

const HF = "hyperframes@0.8.192";
const root = process.cwd();
const hf = (dir) => resolve(root, "hyperframes", dir);
const mediaDir = resolve(root, "public/media");
const compDir = resolve(root, "public/compositions");
mkdirSync(mediaDir, { recursive: true });
mkdirSync(compDir, { recursive: true });

function run(cmd, args, cwd) {
  execFileSync(cmd, args, { cwd, stdio: ["ignore", "inherit", "inherit"] });
}
function hyperframes(args, cwd) {
  run("npx", ["--yes", HF, ...args], cwd);
}
function probe(file) {
  const out = execFileSync("ffprobe", ["-v", "error", "-select_streams", "v:0", "-show_entries", "stream=width,height,r_frame_rate:format=duration", "-of", "csv=p=0", file]).toString().trim().split(/[\n,]/);
  const [num, den] = out[2].split("/").map(Number);
  return { width: Number(out[0]), height: Number(out[1]), fps: Math.round(num / den), duration: Number(Number(out[3]).toFixed(2)) };
}
async function poster(dir, at, out) {
  const tmp = join(dir, "renders/posters");
  rmSync(tmp, { recursive: true, force: true });
  hyperframes(["snapshot", "--at", String(at), "--no-end", "-o", tmp], dir);
  const png = readdirSync(tmp).find((f) => f.startsWith("frame-") && f.endsWith(".png"));
  await sharp(join(tmp, png)).webp({ quality: 82 }).toFile(out);
}
function encode(input, output, extra) {
  run("ffmpeg", ["-v", "error", "-y", "-i", input, ...extra, "-pix_fmt", "yuv420p", "-profile:v", "high", "-movflags", "+faststart", output]);
}

const only = process.env.ONLY ? process.env.ONLY.split(",") : null;
const wants = (name) => !only || only.includes(name);
const mediaTs = resolve(root, "lib/media.ts");
const media = only && existsSync(mediaTs) ? JSON.parse(readFileSync(mediaTs, "utf8").match(/export const media = ([\s\S]*?) as const;/)[1]) : {};

// 1. drawer-to-stack: scrubbed by scroll on the site, so it gets a dense GOP and no B-frames.
if (wants("drawer-to-stack")) {
  const dir = hf("drawer-to-stack");
  mkdirSync(join(dir, "renders"), { recursive: true });
  hyperframes(["check"], dir);
  hyperframes(["render", "--quality", "high", "-o", "renders/drawer-to-stack.mp4"], dir);
  const src = join(dir, "renders/drawer-to-stack.mp4");
  encode(src, join(mediaDir, "drawer-to-stack.mp4"), ["-an", "-c:v", "libx264", "-preset", "slow", "-crf", "21", "-g", "8", "-keyint_min", "8", "-bf", "0"]);
  encode(src, join(mediaDir, "drawer-to-stack-720.mp4"), ["-an", "-vf", "scale=1280:720:flags=lanczos", "-c:v", "libx264", "-preset", "slow", "-crf", "23", "-g", "4", "-keyint_min", "4", "-bf", "0"]);
  await poster(dir, 0, join(mediaDir, "drawer-to-stack.webp"));
  await poster(dir, 4.96, join(mediaDir, "drawer-to-stack-end.webp"));
  media["drawer-to-stack"] = probe(join(mediaDir, "drawer-to-stack.mp4"));
}

// 2. launch-film: the delivery render, with its sound.
if (wants("launch-film")) {
  const dir = hf("launch-film");
  mkdirSync(join(dir, "renders"), { recursive: true });
  hyperframes(["check"], dir);
  hyperframes(["render", "--quality", "high", "-o", "renders/launch-film.mp4"], dir);
  cpSync(join(dir, "renders/launch-film.mp4"), join(mediaDir, "launch-film.mp4"));
  await poster(dir, 1.6, join(mediaDir, "launch-film.webp"));
  media["launch-film"] = probe(join(mediaDir, "launch-film.mp4"));
}

// 3. The two live loops: an MP4 fallback plus the composition itself for <hyperframes-player>.
for (const [name, posterAt] of [["widgets-loop", 3.4], ["wallet-loop", 2.4]]) {
  if (!wants(name)) continue;
  const dir = hf(name);
  mkdirSync(join(dir, "renders"), { recursive: true });
  hyperframes(["check"], dir);
  hyperframes(["render", "--quality", "high", "-o", `renders/${name}.mp4`], dir);
  encode(join(dir, `renders/${name}.mp4`), join(mediaDir, `${name}.mp4`), ["-an", "-c:v", "libx264", "-preset", "slow", "-crf", "22"]);
  await poster(dir, posterAt, join(mediaDir, `${name}.webp`));
  const bundle = join(compDir, name);
  rmSync(bundle, { recursive: true, force: true });
  mkdirSync(bundle, { recursive: true });
  cpSync(join(dir, "index.html"), join(bundle, "index.html"));
  for (const sub of ["compositions", "assets"]) {
    try { cpSync(join(dir, sub), join(bundle, sub), { recursive: true }); } catch {}
  }
  media[name] = probe(join(mediaDir, `${name}.mp4`));
}

writeFileSync(
  mediaTs,
  `// Generated by scripts/build-media.mjs from the HyperFrames compositions under hyperframes/. Do not edit by hand.
export const media = ${JSON.stringify(media, null, 2)} as const;
export type MediaName = keyof typeof media;
`,
);
console.log("media:", media);
