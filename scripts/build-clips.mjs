// Trims the app's UI-test screen recordings into short highlight clips for the site.
// Sources live in the app repository (gitignored there as well); only the derived clips are committed.
import { execFileSync } from "node:child_process";
import sharp from "sharp";
import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const appDir = process.env.GIFTVAULT_APP_DIR ?? resolve(process.cwd(), "../giftcard-manager");
const outDir = resolve(process.cwd(), "public/clips");
mkdirSync(outDir, { recursive: true });

function recording(dir, prefix) {
  const full = join(appDir, "Testing/evidence", dir);
  const hit = readdirSync(full).find((f) => f.startsWith(prefix) && f.endsWith(".mp4"));
  if (!hit) throw new Error(`no recording starting with "${prefix}" in ${full}`);
  return join(full, hit);
}

/** name → { src, segments: [start, end][] (seconds), width } */
const clips = {
  // Search a store, pick it, enter the value, add it: the card appears in the vault.
  "add-card": {
    src: recording("baseline", "testAddCardManually"),
    segments: [[23.4, 27.6], [39.4, 44.4]],
  },
  // Open Starbucks, tap Spent, type 5, the balance drops to $37.10 everywhere.
  "spend": {
    src: recording("baseline", "testSpendUpdatesBalanceEverywhere"),
    segments: [[4.0, 13.5]],
  },
  // Light mode: list, card, flip to the barcode at the register.
  "hurry-register": {
    src: recording("personas", "testP7Hurry"),
    segments: [[3.8, 10.2]],
  },
  // Light mode, landscape: the barcode turns to meet the scanner.
  "hurry-landscape": {
    src: recording("personas", "testP7Hurry"),
    segments: [[35.6, 40.2]],
  },
  // iPhone Duo: list, detail and register on the outer display.
  "duo": {
    src: recording("duo", "testP8DuoLayout"),
    segments: [[7.0, 16.0]],
  },
};

const manifest = {};
for (const [name, clip] of Object.entries(clips)) {
  const parts = clip.segments
    .map(([a, b], i) => `[0:v]trim=start=${a}:end=${b},setpts=PTS-STARTPTS[v${i}]`)
    .join(";");
  const concat = clip.segments.map((_, i) => `[v${i}]`).join("") + `concat=n=${clip.segments.length}:v=1:a=0[cat]`;
  const filter = `${parts};${concat};[cat]fps=30,scale=720:-2:flags=lanczos,format=yuv420p[out]`;
  const mp4 = join(outDir, `${name}.mp4`);
  execFileSync("ffmpeg", ["-v", "error", "-y", "-i", clip.src, "-filter_complex", filter, "-map", "[out]",
    "-c:v", "libx264", "-preset", "slow", "-crf", "23", "-profile:v", "high", "-movflags", "+faststart", "-an", mp4]);
  const framePng = join(outDir, `${name}.frame.png`);
  execFileSync("ffmpeg", ["-v", "error", "-y", "-i", mp4, "-frames:v", "1", framePng]);
  await sharp(framePng).webp({ quality: 80 }).toFile(join(outDir, `${name}.webp`));
  rmSync(framePng);
  const probe = execFileSync("ffprobe", ["-v", "error", "-select_streams", "v:0", "-show_entries", "stream=width,height:format=duration", "-of", "csv=p=0", mp4]).toString().trim().split(/[\n,]/);
  manifest[name] = { width: Number(probe[0]), height: Number(probe[1]), duration: Number(Number(probe[2]).toFixed(2)) };
  process.stdout.write(`${name} `);
}
